export default SYSTEM_STORIES;

/** Get a story by its ID */
export const getStory = (id) => SYSTEM_STORIES.find((s) => s.id === id) || null;

/** Get a feature across all stories */
export const getFeature = (featureId) => {
  for (const story of SYSTEM_STORIES) {
    const feat = story.features.find((f) => f.id === featureId);
    if (feat) return { ...feat, storyId: story.id, chapter: story.chapter };
  }
  return null;
};

/** Count features by status across all stories */
export const getStatsSnapshot = () => {
  let live = 0, partial = 0, planned = 0, disabled = 0;
  for (const story of SYSTEM_STORIES) {
    for (const f of story.features) {
      if (f.status === 'live') live++;
      else if (f.status === 'partial') partial++;
      else if (f.status === 'planned') planned++;
      else disabled++;
    }
  }
  const total = live + partial + planned + disabled;
  return { live, partial, planned, disabled, total, completion: Math.round((live / total) * 100) };
};
